public class IT26101918Lab6Q2A {
    public static void main(String[] args) {
        // Initialize the counter variable
        int i = 1;

        // Use a while loop to iterate from 1 to 10
        while (i <= 10) {
            // Print the number followed by a space, keeping it on the same line
            System.out.print(i + " ");
            // Increment the counter
            i++;
        }
        
        // Print a new line at the end (optional, for clean console formatting)
        System.out.println();
    }
}
